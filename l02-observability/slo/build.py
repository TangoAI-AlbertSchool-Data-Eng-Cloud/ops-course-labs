"""Build the Prometheus rules and the Grafana dashboard from slo/slos.py.

    python slo/build.py
    docker compose restart prometheus grafana

Any Python 3.10 or later; it uses nothing outside the standard library.
Writes prometheus/rules.yml and grafana/dashboards/slo.json.

The alerts follow "multiwindow, multi-burn-rate" alerting, from Google's Site
Reliability Workbook, chapter "Alerting on SLOs". A burn rate is how fast the
error budget is being spent: 1 spends exactly the budget over the SLO period
(30 days here), 14.4 spends 2% of it in one hour. Each alert needs a long
window (is this real?) AND a short one (is it still happening?).
"""

import json
import sys
from pathlib import Path

# slos.py sits next to this file; make it importable from any working folder.
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from slos import FAMILIES, INPUTS, SIGNALS, SLOS, TITLE  # noqa: E402

LAB = HERE.parent   # the lab's root folder, where prometheus/ and grafana/ live

# Every window an SLI is computed over. The short ones feed the alerts; 30d is
# the SLO period, the one the error budget is counted against.
WINDOWS = ["5m", "30m", "1h", "6h", "3d", "30d"]

# (long window, short window, burn rate, severity): the Workbook's table.
ALERTS = [
    ("1h", "5m", 14.4, "page"),     # 2% of the 30-day budget in 1 hour
    ("6h", "30m", 6.0, "page"),     # 5% in 6 hours
    ("3d", "6h", 1.0, "ticket"),    # 10% in 3 days
]


def rules() -> str:
    """prometheus/rules.yml, written as text so no YAML library is needed."""
    # The file starts by saying where it comes from, so nobody edits it by hand.
    out = ["# GENERATED by slo/build.py from slo/slos.py. Edit slos.py, then rebuild.", "groups:"]

    # 1. Helper series some SLIs are built on (slos.INPUTS), e.g. the 0/1
    # series behind a window-based SLI.
    out += ["  - name: slo-inputs", "    rules:"]
    for record, expr in INPUTS:
        out += [f"      - record: {record}", "        expr: |", f"          {expr}"]

    # 2. Every SLI's error ratio over every window, and every objective.
    out += ["  - name: slo-error-ratios", "    rules:"]
    for slo in SLOS:
        for window in WINDOWS:
            # One series per SLO and window, all under the same metric name,
            # told apart by labels: the dashboard and alerts select by label.
            out += [
                "      - record: slo:error_ratio",
                "        expr: |",
                f"          {slo['error_ratio'].format(w=window)}",
                "        labels:",
                f"          slo: {slo['name']}",
                f"          family: {slo['family']}",
                f"          window: {window}",
            ]
        # The objective, as a series too, so a dashboard can draw it.
        out += [
            "      - record: slo:objective",
            f"        expr: vector({slo['objective']})",
            "        labels:",
            f"          slo: {slo['name']}",
        ]

    # 3. Burn-rate alerts: long AND short window above the same burn rate.
    out += ["  - name: slo-burn-rate-alerts", "    rules:"]
    for slo in SLOS:
        budget = round(1 - slo["objective"], 6)   # the share of events allowed to be bad
        for long_w, short_w, burn, severity in ALERTS:
            # An SLO marked "pages": False keeps its ticket and loses its pages.
            if severity == "page" and not slo.get("pages", True):
                continue
            # Burning at `burn` times the allowed rate = a bad share of burn x budget.
            threshold = round(burn * budget, 6)
            out += [
                # Alert names cannot hold a dot: 14.4 becomes 14_4.
                f"      - alert: SLOBurn{burn:g}x".replace(".", "_"),
                "        expr: |",
                f"          slo:error_ratio{{slo=\"{slo['name']}\",window=\"{long_w}\"}} > {threshold}",
                # `and` matches series by their labels; the two windows differ
                # only in `window`, so it is ignored for the match.
                "          and ignoring(window)",
                f"          slo:error_ratio{{slo=\"{slo['name']}\",window=\"{short_w}\"}} > {threshold}",
                "        labels:",
                f"          severity: {severity}",
                f"          slo: {slo['name']}",
                "        annotations:",
                f"          summary: \"{slo['name']}: error budget burning at over {burn:g}x\"",
                f"          description: \"{slo['description']}. Objective {slo['objective']}; "
                f"over {long_w} and {short_w} the bad share exceeds {threshold}.\"",
            ]
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- dashboard
# Grafana stores a dashboard as JSON: a list of panels, each with a position
# on a 24-column grid and the PromQL queries it draws.

def _panel(kind, title, targets, x, y, w, h, unit=None, extra=None):
    """One panel: `kind` is "stat" (a number) or "timeseries" (a graph)."""
    panel = {
        "type": kind, "title": title,
        "gridPos": {"x": x, "y": y, "w": w, "h": h},   # column, row, width, height
        "datasource": {"type": "prometheus", "uid": "prometheus"},
        # Each query gets a letter, A, B, C..., as Grafana's editor does.
        "targets": [{"refId": chr(65 + i), "expr": expr, "legendFormat": legend}
                    for i, (expr, legend) in enumerate(targets)],
        "fieldConfig": {"defaults": {}, "overrides": []},
        "options": {},
    }
    if unit:
        panel["fieldConfig"]["defaults"]["unit"] = unit   # e.g. percentunit, s
    if extra:
        # Thresholds, decimals, colours: anything else on the field defaults.
        for key, value in extra.items():
            panel["fieldConfig"]["defaults"][key] = value
    return panel


def _thresholds(*steps):
    """Colour steps: (None, "red") is the base colour, (0.99, "green") from 0.99 up."""
    return {"thresholds": {"mode": "absolute",
                           "steps": [{"color": c, "value": v} for v, c in steps]}}


def dashboard() -> dict:
    # Panels are placed top to bottom; y is the next free row on the grid.
    panels, y = [], 0

    def row(title):
        """A full-width section heading."""
        nonlocal y
        panels.append({"type": "row", "title": title, "collapsed": False,
                       "gridPos": {"x": 0, "y": y, "w": 24, "h": 1}})
        y += 1

    # Top: the four headline SLOs side by side, one column each.
    row("One SLO per family: the four questions")
    for i, slo in enumerate(s for s in SLOS if s["headline"]):
        name, objective, x = slo["name"], slo["objective"], i * 6
        budget = round(1 - objective, 6)
        sel = f'slo="{name}"'
        # The SLI over the last hour, red below the objective.
        panels.append(_panel(
            "stat", f"{slo['family']}: {name}", [(f'1 - slo:error_ratio{{{sel},window="1h"}}', "")],
            x, y, 6, 4, "percentunit",
            {"decimals": 2, **_thresholds((None, "red"), (objective, "green"))}))
        panels[-1]["description"] = f"{slo['description']}. {FAMILIES[slo['family']]} Objective {objective:.1%}, last hour."
        # What is left of the 30-day budget at the rate of the last 30 days:
        # 100% untouched, 0% spent, negative overspent. A lab that has run
        # for an hour has a one-hour "30 days", and the figure says so.
        panels.append(_panel(
            "stat", "Error budget left (30-day window)",
            [(f'1 - slo:error_ratio{{{sel},window="30d"}} / {budget}', "")],
            x, y + 4, 6, 3, "percentunit",
            {"decimals": 0, **_thresholds((None, "red"), (0, "orange"), (0.25, "green"))}))
        panels[-1]["description"] = (
            "1 - (bad share over the last 30 days) / (1 - objective). In the lab, the "
            "30-day window holds only the time the lab has run, so an hour-long incident "
            "on a two-hour-old lab overspends the budget many times over.")
        # The burn rate over the fast alert's two windows, with the paging line;
        # an SLO that never pages gets the even pace, 1, as its line instead.
        pages = slo.get("pages", True)
        line = 14.4 if pages else 1
        panels.append(_panel(
            "timeseries", "Burn rate (14.4 pages)" if pages else "Burn rate (tickets only)",
            [(f'slo:error_ratio{{{sel},window="5m"}} / {budget}', "5 min"),
             (f'slo:error_ratio{{{sel},window="1h"}} / {budget}', "1 hour")],
            x, y + 7, 6, 7, None,
            # A soft maximum of 20 keeps the 14.4 line in view while nothing burns.
            {"custom": {"thresholdsStyle": {"mode": "line+area"}, "axisSoftMin": 0, "axisSoftMax": 20},
             **_thresholds((None, "transparent"), (line, "red"))}))
        if not pages:
            panels[-1]["description"] = (
                "This SLO never pages: a business outcome lags its cause. Above 1, the "
                "budget is spent faster than the even pace; a ticket opens when the last "
                "three days and the last six hours both are.")
    y += 14   # the tallest column: 4 + 3 + 7 rows

    # Middle: the raw signals, to see WHY an SLO moved.
    row("The signals behind them")
    # Four graphs, chosen in slos.SIGNALS: (title, [(query, legend)], unit).
    for i, (title, targets, unit) in enumerate(SIGNALS[:4]):
        panels.append(_panel("timeseries", title, targets, i * 6, y, 6, 8, unit))
    y += 8    # one row of graphs

    # Bottom: the secondary SLOs, and the state of the platform.
    row("The other workloads, and the platform")
    secondary = [s for s in SLOS if not s["headline"]]
    for i, slo in enumerate(secondary):
        panels.append(_panel(
            "stat", f"{slo['workload']}: {slo['name']}",
            [(f'1 - slo:error_ratio{{slo="{slo["name"]}",window="1h"}}', "")],
            i * 3, y, 3, 4, "percentunit",   # three columns each, from the left
            {"decimals": 2, **_thresholds((None, "red"), (slo["objective"], "green"))}))
    # The three platform panels share what is left of the row's 24 columns.
    x = len(secondary) * 3
    w = (24 - x) // 3
    panels.append(_panel("stat", "Degradation level", [("max(degradation_level)", "")],
                         x, y, w, 4, None,
                         _thresholds((None, "green"), (2, "orange"), (3, "red"))))
    # Red after two missed "nights" (2 x 300 s), not before.
    panels.append(_panel("stat", "Since last good batch run",
                         [("time() - max(batch_last_success_timestamp_seconds)", "")],
                         x + w, y, w, 4, "s", _thresholds((None, "green"), (600, "red"))))
    panels.append(_panel("stat", "LLM $/hour (simulated)",
                         [("sum(rate(llm_cost_usd_total[15m])) * 3600", "")],
                         x + 2 * w, y, w, 4, "currencyUSD", {"decimals": 3}))

    return {
        "title": TITLE,
        "uid": "platform-slos",         # a fixed id, so links to it never break
        "schemaVersion": 41,
        "time": {"from": "now-1h", "to": "now"},
        "refresh": "10s",
        "panels": panels,
        "tags": ["generated"],
        "description": "GENERATED by slo/build.py from slo/slos.py. Edit slos.py, then rebuild.",
    }


def main() -> None:
    # Refuse to build half-configured SLOs: a missing objective would page at once.
    missing = [s["name"] for s in SLOS if s["objective"] is None]
    if missing:
        sys.exit(f"set every objective in slo/slos.py first (missing: {missing})")
    (LAB / "prometheus" / "rules.yml").write_text(rules(), encoding="utf-8")
    (LAB / "grafana" / "dashboards" / "slo.json").write_text(
        json.dumps(dashboard(), indent=2) + "\n", encoding="utf-8")
    print("wrote prometheus/rules.yml and grafana/dashboards/slo.json")


if __name__ == "__main__":
    main()
